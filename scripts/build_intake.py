def load(path):
    with open(path, encoding='utf-8') as f:
        return json.load(f)


def jl(s):
    return json.loads(s) if s else []


def tags(rich):
    """(kind, ID, CN name) for each tagged [term] in a rich text."""
    out = []
    for tag, attr, id_, name in TAG.findall(rich or ''):
        kind = TERM_KIND.get((tag, attr), tag)
        out.append(('neural' if attr == 'passiveSkill' and int(id_) in INNATE else kind, id_, name))
    return out


def plain(rich):
    """CN rich text as the translator reads it: no colour tags, terms kept in brackets, newlines as \\n."""
    s = TAG.sub(lambda m: f'[{m[4]}]', rich or '')
    return COLOR.sub('', s).replace('\r', '').replace('\n', '\\n').strip()


def asset(*parts):
    """Whether a file is in the assets repo (None when the repo isn't checked out)."""
    if not os.path.isdir(ASSETS_DIR):
        return None
    return os.path.exists(os.path.join(ASSETS_DIR, 'data', 'unlisted', *parts))


def icon_note(icon, *folder):
    if not icon:
        return '(none)'
    there = asset(*folder, icon + '.png')
    return icon + ('' if there in (None, True) else '  <!-- not in the assets repo -->')


class Game:
    """The CN client's tables plus what the wiki already has."""

    def __init__(self, full=False):
        for path in (CN_STATS, CN_DB):
            if not os.path.exists(path):
                sys.exit(f'Missing {os.path.relpath(path, ROOT)}: mine the CN client first (see the docstring)')
        self.c = sqlite3.connect(CN_STATS)
        self.c.row_factory = sqlite3.Row
        self.m = sqlite3.connect(CN_DB)
        self.m.row_factory = sqlite3.Row
        self.full = full
        self.pilots = load(os.path.join(DB, 'pilots.json'))
        self.mechs = load(os.path.join(DB, 'mechs.json'))
        self.skills = load(os.path.join(DB, 'skills.json'))
        self.modules = load(os.path.join(DB, 'modules.json'))
        self.partitions = load(os.path.join(DB, 'neural_partitions.json'))
        self.glossary = load(GLOSSARY)
        INNATE.update(i for (i,) in self.c.execute('select AutoPassiveSkill from ConfigDataPilotComputerUnitInfo '
                                                   'where AutoPassiveSkill'))
        # CN name -> what the wiki calls it, for terms the CN text leaves untagged or tags with
        # a different ID than the wiki uses (the same buff often has several IDs).
        self.cn2en = {}
        for kind, table, col in (('buf', 'ConfigDataActorBufInfo', 'NameDescStrKey_EN'),
                                 ('skill', 'ConfigDataActiveSkillInfo', 'NameStrKey_EN'),
                                 ('terrain', 'ConfigDataBattleTerrainEffectInfo', 'NameStrKey_EN')):
            cn = dict(self.c.execute(f'select ID, {col} from {table}'))
            for key, entry in self.glossary.get(kind, {}).items():
                if key.isdigit() and cn.get(int(key)):
                    self.cn2en.setdefault(cn[int(key)], (entry['name'], f'{kind} {key}'))
        # ...and the names other texts tag with an ID the wiki has.
        for table, col in (('ConfigDataMainSkillInfo', 'SkillDescStrKey_EN'), ('ConfigDataPassiveSkillInfo', 'SkillDescStrKey_EN'),
                           ('ConfigDataActiveSkillInfo', 'SkillDescStrKey_EN'), ('ConfigDataActorBufInfo', 'BuffDescStrKey_EN')):
            for (text,) in self.c.execute(f'select {col} from {table} where {col} like "%[%"'):
                for kind, id_, name in tags(text):
                    entry = self.wiki_term(kind, id_)
                    if entry:
                        self.cn2en.setdefault(name, (entry['name'], f'{kind} {id_}'))
        for key, entry in self.skills.items():
            row = key.isdigit() and entry.get('name') and self.skill_row(int(key))
            if key.startswith('neural:') and entry.get('name'):
                row = self.row('ConfigDataPassiveSkillInfo', int(key[len('neural:'):]))
            if row:
                self.cn2en.setdefault(row['NameStrKey_EN'], (entry['name'], f'skill row {key}'))
        # Effect-list signature -> existing partition, to spot shared α/β/γ.
        self.partition_by_effects = {}
        for key, part in self.partitions.items():
            sig = tuple((e['min'], e['skill']) for e in part.get('effects', []))
            self.partition_by_effects.setdefault(sig, key)

    def row(self, table, id_):
        return self.c.execute(f'select * from {table} where ID = ?', (id_,)).fetchone()

    def skill_row(self, id_):
        return self.row('ConfigDataMainSkillInfo', id_) or self.row('ConfigDataPassiveSkillInfo', id_)

    def neural_key(self, id_):
        """An innate neural core's skills.json key: "neural:<ID>" when a main skill has the same ID."""
        return f'neural:{id_}' if self.row('ConfigDataMainSkillInfo', int(id_)) else str(id_)

    def wiki_term(self, kind, id_):
        """The wiki's entry for a tagged term: glossary.json, or a skills.json row for pilot/module skills."""
        if kind == 'neural':
            return self.skills.get(self.neural_key(id_))
        if kind == 'passive':
            return self.skills.get(id_) or self.glossary['skill'].get(id_)
        return self.glossary.get(kind, {}).get(id_)


class Form:
    """One intake form: markdown lines plus the new glossary terms its text uses."""

    def __init__(self, game):
        self.g = game
        self.lines = []
        self.new_terms = {}  # (kind, id) -> CN name, in first-seen order

    def add(self, *lines):
        self.lines.extend(lines)

    def term_notes(self, rich):
        """One line per [term] in the text: its ID and the wiki's English name, or that it's new."""
        g = self.g
        notes, seen = [], set()
        found = tags(rich)
        for kind, id_, name in found:
            if (kind, id_, name) in seen:
                continue
            seen.add((kind, id_, name))
            entry = g.wiki_term(kind, id_)
            if entry:
                notes.append(f'[{name}] = {kind} {id_}, wiki: "{entry["name"]}"')
            elif name in g.cn2en:
                en, ref = g.cn2en[name]
                notes.append(f'[{name}] = {kind} {id_}; wiki has it as {ref}: "{en}"')
            else:
                notes.append(f'[{name}] = {kind} {id_}, NEW (see New glossary entries)')
                self.new_terms.setdefault((kind, int(id_)), name)
        tagged = {n for _, _, n in found}
        for name in BRACKET.findall(COLOR.sub('', TAG.sub('', rich or ''))):
            if name in tagged or name in seen:
                continue
            seen.add(name)
            if name in g.cn2en:
                en, ref = g.cn2en[name]
                notes.append(f'[{name}] untagged; wiki has it as {ref}: "{en}"')
            else:
                notes.append(f'[{name}] untagged, no wiki entry (plain text, or find its ID)')
        return notes

    def text(self, label, rich, name_cn=None, indent=''):
        """A CN text (and optionally its name) with blank EN lines for the translator."""
        lines = []
        if name_cn is not None:
            lines += [f'- CN name: {name_cn}', '- EN name: ']
        lines += [f'- {label}CN: {plain(rich)}', f'- {label}EN: ']
        notes = self.term_notes(rich)
        if notes:
            lines += ['- Terms: ' + notes[0], *[f'  {n}' for n in notes[1:]]]
        self.add(*[indent + line for line in lines])

    def heading(self, heading, skill_id, key=None):
        """Write a skill's heading; True when the wiki has the skill already and the form skips it."""
        entry = self.g.skills.get(key or str(skill_id))
        if entry and not self.g.full:
            self.add('', f'{heading}, already in the wiki: "{entry.get("name")}"')
            return True
        self.add('', heading)
        if entry:
            self.add(f'- Wiki now: "{entry.get("name")}"')
        return False

    def glossary_section(self):
        """New buffs/skills the text refers to, following the terms their own descriptions use."""
        g = self.g
        if not self.new_terms:
            return
        self.add('', '## New glossary entries',
                 '<!-- → data/glossary.json `buf`/`skill`/`terrain` (a "passive" is a skill row: glossary `skill`;',
                 '     a "neural" is an innate neural core: a data/db/skills.json row, tagged <neural ID=...>),',
                 '     keyed by the ID; tag every reference with it -->')
        done = {}  # (kind, id) -> CN name
        while len(done) < len(self.new_terms):
            for (kind, id_), name in list(self.new_terms.items()):
                if (kind, id_) in done:
                    continue
                twin = next((f'{k} {i}' for (k, i), n in done.items() if n == name), None)
                done[(kind, id_)] = name
                self.add('', f'### {kind} {id_}: {name}')
                if twin:
                    self.add(f'- Same name as {twin} above: one glossary entry can do for both (tag both with its ID)')
                if kind == 'buf':
                    r = g.row('ConfigDataActorBufInfo', id_)
                    if r and r['Icon']:
                        self.add(f'- Icon (only if the popup should show one): {r["Icon"]}')
                    desc = r and r['BuffDescStrKey_EN']
                elif kind == 'skill':
                    r = g.row('ConfigDataActiveSkillInfo', id_)
                    if r:
                        self.add(f'- AP: {r["ApCost"] or 0} · Icon: {icon_note(r["Icon"], "pilot_skills")}')
                    desc = r and r['SkillDescStrKey_EN']
                elif kind == 'neural':
                    r = g.row('ConfigDataPassiveSkillInfo', id_)
                    self.add(f'- skills.json key: {g.neural_key(id_)}')
                    if r:
                        self.add(f'- Icon: {icon_note(r["Icon"], "pilot_skills")}')
                    desc = r and r['SkillDescStrKey_EN']
                elif kind == 'passive':
                    r = g.skill_row(id_)
                    if r:
                        self.add(f'- Icon: {icon_note(r["Icon"], "pilot_skills")}')
                    desc = r and r['SkillDescStrKey_EN']
                elif kind == 'terrain':
                    r = g.row('ConfigDataBattleTerrainEffectInfo', id_)
                    desc = r and r['DescStrKey_EN']
                else:
                    desc = None
                self.text('', desc or '', name_cn=name)

    def write(self, path, force):
        if os.path.exists(path) and not force:
            print(f'  kept {os.path.relpath(path, ROOT)} (exists; --force to overwrite)')
            return
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, 'w', encoding='utf-8', newline='\n') as f:
            f.write('\n'.join(self.lines).rstrip() + '\n')
        print(f'  wrote {os.path.relpath(path, ROOT)}')


def skill_type(g, main):
    """The wiki's `type` for a MainSkillInfo row, from its active skills' categories."""
    cats = []
    for w in jl(main['WeaponActiveSkillList']):
        a = g.row('ConfigDataActiveSkillInfo', w['Id'])
        cat = (a['Category'] or '').replace('ActiveSkillCategory_', '') if a else ''
        if cat and cat not in cats:
            cats.append(cat)
    if not cats:
        return 'Order'
    return cats[0] if len(cats) == 1 else '/'.join(cats) + '  <!-- mixed: pick one -->'


def skill_block(f, title, skill_id, innate=False):
    g = f.g
    # An innate neural core is always the passive, even when a main skill shares its ID.
    r = g.row('ConfigDataPassiveSkillInfo', skill_id) if innate else g.skill_row(skill_id)
    if r is None:
        f.add('', f'### {title}: {skill_id}', '- Not in the CN tables')
        return
    key = g.neural_key(skill_id) if innate else str(skill_id)
    if f.heading(f'### {title}: {key}', skill_id, key):
        return
    is_main = 'WeaponActiveSkillList' in r.keys()
    if is_main:
        f.add(f'- Type: {skill_type(g, r)}',
              f'- AP cost: {r["ApCost"] or 0}',
              f'- Cooldown: {r["ShowCd"] or ""}')
        if r['MatchEquipmentTypeStrKey_EN']:
            f.add(f'- Weapon type: {r["MatchEquipmentTypeStrKey_EN"]}')
    else:
        f.add('- Type: Passive')
    if 'PP' in (r['SkillDescStrKey_EN'] or ''):
        f.add('- Resource: PP  <!-- the text mentions PP: check -->')
    f.add(f'- Icon name: {icon_note(r["Icon"], "pilot_skills")}')
    f.text('', r['SkillDescStrKey_EN'], name_cn=r['NameStrKey_EN'])


def pilot_form(g, pid, version):
    p = g.row('ConfigDataPilotInfo', pid)
    if p is None:
        sys.exit(f'No pilot {pid} in the CN tables')
    info = g.m.execute('select * from pilots where pilot_id = ?', (pid,)).fetchone()
    stars = jl(p['StarPropertiesTemplateId'])
    templates = [g.row('ConfigDataPilotPropertiesTemplateInfo', t) for t in stars]
    top = templates[-1]
    pic = g.row('ConfigDataCharacterPicture', p['CharacterPictureId'])
    f = Form(g)
    name_cn = p['NameStrKey_EN']
    game_prof = (p['Profession'] or '').replace('PilotProfessionType_', '')
    profession, occupation = PROFESSION.get(game_prof, (game_prof, info['class'] if info else ''))
    f.add(PILOT_CHECKLIST, '', f'# Pilot {pid}: {name_cn}' + (' (already in the wiki)' if str(pid) in g.pilots else ''))

    f.add('', '## Basics', '<!-- → data/db/pilots.json row, keyed by Pilot ID -->', '',
          f'- Pilot ID: {pid}',
          f'- CN name: {name_cn}', '- Pilot Name (EN): ',
          f'- CN real name: {p["RealNameStrKey_EN"]}',
          f'- Real Name (EN): {p["EnglishName"] or ""}' + ('  <!-- from the game data: check -->' if p['EnglishName'] else ''),
          f'- Gender: {(p["Gender"] or "").replace("PilotGenderType_", "")}',
          f'- Profession: {profession}',
          f'- Occupation: {occupation}',
          f'- Quality: {(top["Rarity"] or p["Rarity"] or "").replace("RarityType_", "")}',
          f'- License: {info["drive_classes_p_max"] if info else ""}',
          f'- Game version introduced: {version or ""}')
    f.add('', '### Bio', '<!-- → `introduction` -->')
    f.text('', p['DescStrKey_EN'])

    icon = pic['Icon'] if pic else ''
    f.add('', '## Images',
          f'- Portrait (half-body): {icon_note(icon + "_half", "pilot_images_half")}  <!-- portrait_icon -->',
          f'- Avatar (full portrait): {icon_note(icon + "_Raw", "pilot_images_raw")}  <!-- avatar_icon -->')

    # Max potential + Bionic Computer neurons, as the wiki shows them (see README "Stat conventions").
    st = g.m.execute('select * from pilot_stats where pilot_id = ? order by potential desc', (pid,)).fetchone()
    f.add('', '## Attributes', '<!-- → `stats`: max potential + neural adds × 1.10 (can be 1 off the game screen) -->')
    if st:
        for wiki, col in (('combat', 'melee'), ('assault', 'assault'), ('shooting', 'ranged'),
                          ('tactics', 'tactical'), ('defense', 'defense'), ('engineering', 'mechanics')):
            f.add(f'- {wiki}: {st[col] + round((st["neural_" + col] or 0) * 1.10)}')
    f.add(f'- ap_init: {top["PilotAPInitBase"]}', f'- ap_max: {top["PilotAPMaxBase"]}',
          f'- ap_regen: {top["PilotAPRecoverBase"]}')

    talents = []
    for t in templates:
        if t['TalentPassiveSkillId'] and t['TalentPassiveSkillId'] not in talents:
            talents.append(t['TalentPassiveSkillId'])
    f.add('', '## Talents', '<!-- → data/db/skills.json rows (kind "talent", `effect`); `talents` = [basic, ascended] -->')
    basic_text = None
    for i, tid in enumerate(talents):
        r = g.row('ConfigDataPassiveSkillInfo', tid)
        title = 'Basic Talent' if i == 0 else 'Ascended Talent'
        if f.heading(f'### {title}: {tid}', tid):
            basic_text = r['SkillDescStrKey_EN']
            continue
        f.add(f'- Icon name: {icon_note(r["Icon"], "pilot_skills")}')
        desc = r['SkillDescStrKey_EN'] or ''
        if i == 0:
            basic_text = desc
            f.text('', desc, name_cn=r['NameStrKey_EN'])
        elif basic_text and desc.startswith(basic_text):
            f.add('- Same name and text as the basic talent, plus (after a line break):')
            f.text('', desc[len(basic_text):].lstrip('\n'))
        else:
            f.text('', desc, name_cn=r['NameStrKey_EN'])

    f.add('', '## Skills',
          '<!-- The profession skill + 8 neural skills in board order → data/db/skills.json rows (kind "skill"),',
          '     referenced by the neurons in data/db/pilot_neurons.json. Actives: `describe`, `type`, `ap`, `cd`;',
          '     passives: `effect`, no `type`. -->')
    units = [g.row('ConfigDataPilotComputerUnitInfo', u)
             for u in jl(g.row('ConfigDataPilotComputerTemplateInfo', p['ComputerTemplateId'])['ComputerUnitList'])]
    units = sorted((u for u in units if u), key=lambda u: u['UnitSequence'] or 0)
    for u in units:
        if u['AutoPassiveSkill']:
            skill_block(f, 'Skill 0 (Profession, innate)', u['AutoPassiveSkill'], innate=True)
    # The starting skill is the board's 8th neural skill, but the game gives it from PilotInfo rather than
    # from a neuron unit; the wiki puts it in a neuron of its own, <pilot ID>36.
    for sid in jl(p['InitMainSkillIds']) + jl(p['InitPassiveSkillIds']):
        skill_block(f, f'Skill 1 (starting skill, neuron {pid}36)', sid)
    n = 2
    for u in units:
        sid = u['LearnMainSkill'] or u['LearnPassiveSkill']
        if sid:
            skill_block(f, f'Skill {n} (neuron {u["ID"]})', sid)
            n += 1

    zones = [g.row('ConfigDataPilotChipZoneInfo', z)
             for z in jl(g.row('ConfigDataPilotChipTemplateInfo', p['ChipTemplateId'])['PilotChipZoneInfoList'])]
    f.add('', '## Neural Drive', '<!-- → `neural` on the pilots.json row: one { partition, slots } per zone.',
          '     Slot colours: Attack = red, Critical = blue, Dodge = yellow. -->')
    for z in zones:
        zone = z['NameStrKey_EN']
        slots = [CHIP_SLOT.get(s, s) for s in jl(z['SetupChipTypeList'])]
        effects = [g.row('ConfigDataPilotChipZoneActiveEffectInfo', e) for e in jl(z['ActiveEffectInfos'])]
        sig = tuple((str(e['PowerCostSumMin']), str(e['EffectPassiveSkillId'])) for e in effects)
        existing = g.partition_by_effects.get(sig)
        key = ZONE_KEY.get(zone, zone)
        f.add('', f'### {zone}', f'- Slots: {"/".join(slots)} ({"/".join(CHIP_COLOR.get(s, s) for s in slots)})')
        if existing and not g.full:
            f.add(f'- Partition: reuse `{existing}`, already in the wiki')
            continue
        if existing:
            f.add(f'- Partition: `{existing}` (in the wiki)')
        else:
            suggested = f'{occupation.lower()}-{key}' if key in ('alpha', 'beta') else f'{pid}-{key}'
            f.add(f'- Partition: NEW `{suggested}` (type "{"Gamma" if key.startswith("gamma") else key.capitalize()}")')
        for e in effects:
            sid = e['EffectPassiveSkillId']
            entry = g.skills.get(str(sid))
            if entry and not g.full:
                f.add(f'- {e["PowerCostSumMin"]}: {sid}, already in the wiki: "{entry.get("name")}"')
                continue
            r = g.row('ConfigDataPassiveSkillInfo', sid)
            f.add(f'- {e["PowerCostSumMin"]}: {sid}, Icon: {icon_note(r["Icon"], "pilot_skills")}')
            f.text('', r['SkillDescStrKey_EN'], name_cn=r['NameStrKey_EN'], indent='  ')

    f.glossary_section()
    return f


def part_rows(g, body_id):
    suit = g.c.execute('select * from ConfigDataTacticalUnitSuitInfo where WapPartBodyId = ? and ID < 10000',
                       (body_id,)).fetchone()
    if suit is None:
        sys.exit(f'No ST with body part {body_id} in the CN tables')
    return suit, [g.row('ConfigDataWapBodyInfo', suit['WapPartBodyId']),
                  g.row('ConfigDataWapArmInfo', suit['WapPartLeftArmId']),
                  g.row('ConfigDataWapArmInfo', suit['WapPartRightArmId']),
                  g.row('ConfigDataWapLegInfo', suit['WapPartLegId'])]


# Part stat -> (base column per part table, level template column, grade multiplier column).
STAT_COLUMNS = {
    'hp': ({'Body': 'WapBodyHPMaxBase', 'Arm': 'WapArmHPMaxBase', 'Leg': 'WapLegHPMaxBase'},
           'HPMaxLevelEnhanceTeamplateId', 'MaxHPEnhanceMulti'),
    'armor': ({'Body': 'WapBodyArmorBase', 'Arm': 'WapArmArmorBase', 'Leg': 'WapLegArmorBase'},
              'ArmorLevelEnhanceTeamplateId', 'ArmorEnhanceMulti'),
    'antiriot': ({'Body': 'WapBodyAntiCriticalAppendBase'}, 'AntiCriticalAppendLevelEnhanceTeamplateId',
                 'AntiCriticalAppendEnhanceMulti'),
    'hit': ({'Arm': 'HitValueBase'}, 'HitValueLevelEnhanceTeamplateId', 'HitValueEnhanceMulti'),
    'dodge': ({'Leg': 'WapLegDodgeBase'}, 'DodegLevelEnhanceTeamplateId', 'DodgeEnhanceMulti'),
    'fire': ({'Body': 'FireValueBase'}, 'FireValueLevelEnhanceTeamplateId', 'FireValueEnhanceMulti'),
}
PART_STATS = {'Body': ('hp', 'armor', 'antiriot'), 'L-Arm': ('hp', 'armor', 'hit'),
              'R-Arm': ('hp', 'armor', 'hit'), 'Legs': ('hp', 'armor', 'dodge')}


def max_stat(g, part, stat):
    """A part stat at level 70 and its top grade: base × level multiplier × grade multiplier, rounded down
    (the mined st_max table rounds instead, which is 1 over the wiki's values about half the time)."""
    bases, level_col, grade_col = STAT_COLUMNS[stat]
    kind = next(k for k in bases if any(c.startswith(f'Wap{k}') for c in part.keys()))
    value = part[bases[kind]] or 0
    if part[level_col]:
        levels = jl(g.row('ConfigDataLevelEnhanceTemplateInfo', part[level_col])['LevelEnhanceMulti'])
        value *= max(levels, key=lambda e: e['Level'])['EnhanceMulti']
    grade = g.row('ConfigDataQualityEnhanceTemplateInfo', jl(part['QualityEnhanceTemplateId'])[-1])
    return int(value * (grade[grade_col] or 1))


def module_levels(g, parts):
    """Module family -> level: each part's top grade adds its modules' levels."""
    levels = {}
    for part in parts:
        top = jl(part['QualityEnhanceTemplateId'])[-1]
        for e in jl(g.row('ConfigDataQualityEnhanceTemplateInfo', top)['BasicWapEntryInfoList']):
            levels[e['Id']] = levels.get(e['Id'], 0) + e['Value']
    return levels


def module_block(f, family, level, note=''):
    g = f.g
    entry = g.row('ConfigDataWapEntryInfo', family)
    level_ids = jl(entry['EntryLevelIdList'])
    levels = [g.row('ConfigDataPassiveSkillInfo', l) for l in level_ids]
    family = level_ids[0] // 10  # the wiki's key: level IDs are <family><level> (hidden modules' entry IDs aren't)
    wiki = g.modules.get(str(family))
    if wiki and not g.full:
        f.add('', f'### Module {family}: level {level}/{len(levels)}{note}, already in the wiki: "{wiki["name"]}"')
        return
    f.add('', f'### Module {family}: level {level}/{len(levels)}{note}',
          f'- Icon name: {icon_note(levels[-1]["Icon"], "pilot_skills" if levels[-1]["Icon"].startswith("Icon_skill_") else "mech_modules")}')
    f.add(f'- CN name: {entry["NameStrKey_EN"]}', '- EN name: ')
    # Levels whose text differs only in its numbers share one translation; each level's numbers are listed.
    groups = []
    for i, r in enumerate(levels, 1):
        text = plain(r['SkillDescStrKey_EN'])
        shape = NUMBER.sub('#', text)
        if groups and groups[-1][0] == shape:
            groups[-1][1].append((i, NUMBER.findall(text)))
        else:
            groups.append((shape, [(i, NUMBER.findall(text))], r))
    for shape, members, r in groups:
        first, last = members[0][0], members[-1][0]
        span = f'Lv{first}' if first == last else f'Lv{first}-{last}'
        mark = len(f.lines)
        f.text(f'{span} ', levels[last - 1]['SkillDescStrKey_EN'])
        if first != last:
            f.lines.insert(mark + 2, f'- {span} numbers, in order (the EN text above is Lv{last}): '
                           + ' · '.join(f'Lv{i}: {", ".join(nums)}' for i, nums in members))


def st_form(g, body_id, version):
    suit, parts = part_rows(g, body_id)
    body, larm, rarm, legs = parts
    kind = (body['SizeType'] or '').replace('WapPartSizeType_', '')
    wap = (suit['IconPath'] or '').replace('Icon_mecha_', '')
    f = Form(g)
    f.add(ST_CHECKLIST, '', f'# ST {body_id}: {suit["NameStrKey_EN"]}' + (' (already in the wiki)' if str(body_id) in g.mechs else ''))

    f.add('', '## Basics', '<!-- → data/db/mechs.json row, keyed by the Body part ID -->', '',
          f'- Mech ID: {body_id}',
          f'- CN name: {suit["NameStrKey_EN"]}',
          f'- Mech Name (EN): {suit["EnglishName"] or ""}' + ('  <!-- from the game data: check -->' if suit['EnglishName'] else ''),
          f'- Type: {kind}',
          f'- Quality: {(suit["Rarity"] or "").replace("RarityType_", "")}',
          f'- Game version introduced: {version or ""}',
          '- Dispatch version: ')
    f.add('', '### Flavor text', '<!-- → `introduce` -->')
    f.text('', suit['DescStrKey_EN'])

    skins = []
    skin_dir = os.path.join(ASSETS_DIR, 'data', 'unlisted', 'mechs', 'Skins', kind)
    if os.path.isdir(skin_dir):
        prefix = f'Img_Skin_{wap}_'
        skins = sorted(n[len(prefix):-4] for n in os.listdir(skin_dir) if n.startswith(prefix) and n.endswith('.png'))
    raw = wap and f'{wap}_SN_Raw'
    f.add('', '## Images',
          f'- Icon: {icon_note(suit["IconPath"], "mechs", "Icon", kind)}  <!-- icon -->',
          f'- Portrait (Raw): {icon_note("Icon_mecha_" + raw if raw else "", "mechs", "Raw", kind)}',
          f'- CDN mecha icon: {body["Icon"] or ""}  <!-- mecha_icon -->',
          f'- CDN portrait key: icon_lihui_{wap}  <!-- portrait_icon -->',
          f'- Alternate skins: {", ".join(skins) or "none in the assets repo"}  <!-- skins -->')

    f.add('', '## Stats', '<!-- the table values: mech row (level 1 base + max-level firepower and output),',
          '     then each mech_parts.json row at level 70, top grade -->',
          '', '### Mech row',
          f'- output: {body["WapBodyPowerBase"]}', f'- durable: {body["WapBodyHPMaxBase"]}',
          f'- armor: {body["WapBodyArmorBase"]}', f'- fire: {body["FireValueBase"]}',
          f'- antiriot: {body["WapBodyAntiCriticalAppendBase"]}', f'- firepower: {max_stat(g, body, "fire")}')
    for label, part in zip(('Body', 'L-Arm', 'R-Arm', 'Legs'), parts):
        f.add('', f'### {label}: {part["ID"]}', f'- weight: {part["Weight"]}')
        for stat in PART_STATS[label]:
            f.add(f'- {stat}: {max_stat(g, part, stat)}')
    f.add(f'- move: {(legs["MovePointMaxBase"] or 0) // 1000}  <!-- not stored -->')

    f.add('', '## Modules', '<!-- → `modules`: { "family": "<id>", "level": <n> }; new families → data/db/modules.json -->')
    for family, level in module_levels(g, parts).items():
        module_block(f, family, level)
    # Hidden modules switch on at a part grade (e.g. Asteria's); the wiki lists some of them.
    hidden = {}
    for col in ('BodyHiddenWapEntry', 'LeftArmHiddenWapEntry', 'RightArmHiddenWapEntry', 'LegHiddenWapEntry'):
        for e in jl(suit[col]):
            family = g.c.execute('select ID from ConfigDataWapEntryInfo where EntryLevelIdList like ?',
                                 (f'%{e["ID"]}%',)).fetchone()
            if family:
                hidden[family[0]] = max(hidden.get(family[0], 0), e['Level'])
    grade = (suit['HiddenWapEntryActiveMinQuality'] or '').replace('WapPartQualityType_', '')
    for family, level in hidden.items():
        module_block(f, family, level, f' (hidden, active from grade {grade}: list it only if the game shows it)')

    f.glossary_section()
    return f


def new_ids(g):
    pilots = [r['ID'] for r in g.c.execute('select ID from ConfigDataPilotInfo where IsPlayerPilot = 1 order by ID')
              if str(r['ID']) not in g.pilots]
    # Collectible STs only (the mined `sts` table); the suit table also holds test and enemy suits.
    sts = [r['body_id'] for r in g.m.execute('select body_id, name from sts where st_id < 10000 order by st_id')
           if str(r['body_id']) not in g.mechs and '废弃' not in (r['name'] or '')]
    return pilots, sts


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    ap.add_argument('ids', nargs='*', type=int, help='pilot IDs and/or ST body part IDs (default: every new one)')
    ap.add_argument('--version', help='prefill "Game version introduced"')
    ap.add_argument('--full', action='store_true', help="ask for every text, even what the wiki already has")
    ap.add_argument('--force', action='store_true', help='overwrite existing forms')
    args = ap.parse_args()
    g = Game(full=args.full)
    if args.ids:
        pilots = [i for i in args.ids if g.row('ConfigDataPilotInfo', i)]
        sts = [i for i in args.ids if i not in pilots]
    else:
        pilots, sts = new_ids(g)
        print(f'CN client has {len(pilots)} pilot(s) and {len(sts)} ST(s) the wiki doesn\'t')
    for pid in pilots:
        pilot_form(g, pid, args.version).write(os.path.join(OUT, f'pilot-{pid}.md'), args.force)
    for bid in sts:
        st_form(g, bid, args.version).write(os.path.join(OUT, f'st-{bid}.md'), args.force)


if __name__ == '__main__':
    main()
