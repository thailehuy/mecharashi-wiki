#!/usr/bin/env python3
"""Write a translation intake form for every CN signature weapon and crafted
backpack the wiki doesn't have yet: data/intake/weapon-<SSSR ID>.md and
data/intake/backpack-<ID>.md. The pilot/ST counterpart is build_intake.py,
whose form machinery this reuses.

Run it after a CN game update, once the CN client has been mined again (see
build_intake.py). Everything the game data gives is filled in already: IDs,
icons, stats, slot, passives and the Workshop recipe with each ingredient
resolved to the wiki's backpacks.json / weapons.json / materials.json keys.
What's left for the translator are the `EN:` lines under each piece of Chinese
text and the names of new crafting materials. Once they're filled in, hand the
form to Claude to add the item.

A weapon is new when the CN client's Arms Production
(ConfigDataItemExchangeBlueprintInfo) makes an SSSR weapon that
data/db/weapons.json doesn't have; its form also covers the UR version it's
made from. A backpack is new when the CN client's Backpack Crafting
(ConfigDataBackpackMakingFormulaInfo) makes a backpack that
data/db/backpacks.json doesn't have; an ingredient backpack the wiki doesn't
have gets a form of its own. Forms that already exist are kept unless --force
is given.

    python3 scripts/build_item_intake.py                     # every new weapon and crafted backpack
    python3 scripts/build_item_intake.py 40215123 60902426   # these SSSR weapon / backpack IDs, even if the wiki has them
    python3 scripts/build_item_intake.py --version 3.8       # prefill "Game version introduced"
    python3 scripts/build_item_intake.py --full 40215123     # ask for every text, even what the wiki has
"""
