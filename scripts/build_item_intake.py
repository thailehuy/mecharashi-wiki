def strip(value, prefix):
    return (value or '').replace(prefix, '')


def file_note(icon, *folder):
    """The icon, flagged when the assets repo is checked out and doesn't have it."""
    if not icon:
        return '(none)'
    if os.path.isdir(ASSETS_DIR) and not os.path.exists(os.path.join(ASSETS_DIR, 'data', *folder, icon + '.png')):
        return icon + '  <!-- not in the assets repo -->'
    return icon


def sizes(row):
    return '/'.join(strip(s, 'WapPartSizeType_') for s in jl(row['WapPartSizeLimitList'])) or 'Light/Medium/Heavy'


def quality(row):
    """The wiki's quality: the game's SSR with a Composite (SP) initial grade is UR."""
    q = strip(row['Rarity'], 'RarityType_')
    return 'UR' if q == 'SSR' and row['InitQuality'] == 'WapPartQualityType_SP' else q


class Items(Game):
    """Game, plus the wiki's weapons, backpacks and materials and the global client's item names."""

    def __init__(self, full=False):
        super().__init__(full)
        self.weapons = load(os.path.join(DB, 'weapons.json'))
        self.backpacks = load(os.path.join(DB, 'backpacks.json'))
        self.materials = load(os.path.join(DB, 'materials.json'))
        # Material slugs come from the item's English name in the global client (as build_crafting.py makes them).
        self.global_items = {}
        if os.path.exists(GLOBAL_STATS):
            gc = sqlite3.connect(GLOBAL_STATS)
            self.global_items = dict(gc.execute('select ID, NameStrKey_EN from ConfigDataNormalItemInfo'))
        self.backpack_skills = {b['skill']['id']: (k, b['name']) for k, b in self.backpacks.items()
                                if b.get('skill', {}).get('id')}
        self.pilot_names = [(r['NameStrKey_EN'], r['ID']) for r in
                            self.c.execute('select ID, NameStrKey_EN from ConfigDataPilotInfo where IsPlayerPilot = 1')
                            if r['NameStrKey_EN']]

    def recipe(self, result):
        return self.c.execute('select * from ConfigDataItemExchangeBlueprintInfo where ResultItemId = ?', (result,)).fetchone()

    def material(self, item_id):
        """(materials.json slug, None) for an item the wiki has, else (None, its CN item row)."""
        if item_id in FIXED_MATERIALS:
            return FIXED_MATERIALS[item_id], None
        name = self.global_items.get(item_id)
        if name and slug(name) in self.materials:
            return slug(name), None
        return None, self.row('ConfigDataNormalItemInfo', item_id)


class ItemForm(Form):
    def __init__(self, game):
        super().__init__(game)
        self.new_materials = {}   # item ID -> CN item row
        self.new_backpacks = []   # ingredient backpack IDs the wiki doesn't have

    def ingredient(self, entry, label):
        """One crafting-list line: the wiki entry as it goes in `crafting`, and what it is."""
        self.add(f'- `{entry}`  <!-- {label} -->')

    def material_line(self, item_id, qty):
        key, row = self.g.material(item_id)
        if key:
            self.ingredient(f'{{"material": "{key}", "qty": {qty}}}', f'item {item_id}, already in the wiki')
        else:
            self.new_materials.setdefault(item_id, row)
            name = row['NameStrKey_EN'] if row else '?'
            self.ingredient(f'{{"material": "<slug>", "qty": {qty}}}', f'item {item_id} {name}: NEW, see New materials')

    def backpack_line(self, backpack_id, qty, composite=False):
        g = self.g
        extra = ', "composite": true' if composite else ''
        wiki = g.backpacks.get(str(backpack_id))
        if wiki:
            note = f'"{wiki["name"]}", already in the wiki'
        else:
            r = g.row('ConfigDataBackpackInfo', backpack_id)
            note = f'{r["NameStrKey_EN"] if r else "?"}: NEW, see backpack-{backpack_id}.md'
            if backpack_id not in self.new_backpacks:
                self.new_backpacks.append(backpack_id)
        self.ingredient(f'{{"backpack": "{backpack_id}", "qty": {qty}{extra}}}', note)

    def materials_section(self):
        """New crafting materials, with the Arms Production recipe of each (which may name more new ones)."""
        g = self.g
        if not self.new_materials:
            return
        self.add('', '## New materials', '<!-- → data/db/materials.json, keyed by a slug of the EN name: `label`, `item_icon`,',
                 '     and `crafting` when it has a recipe -->')
        done = set()
        while len(done) < len(self.new_materials):
            for item_id, row in list(self.new_materials.items()):
                if item_id in done:
                    continue
                done.add(item_id)
                self.add('', f'### Item {item_id}')
                if row is None:
                    self.add('- Not in the CN item table')
                    continue
                self.add(f'- CN name: {row["NameStrKey_EN"]}', '- EN name: ',
                         f'- item_icon: {file_note(row["Icon"], "items")}')
                r = g.recipe(item_id)
                if r:
                    self.add('- Recipe (Arms Production):')
                    for m in jl(r['ExchangeMaterials']):
                        self.material_line(m['ItemId'], m['Count'])


# ── Weapons ──────────────────────────────────────────────────────────────────

def guess_pilot(g, text):
    """The wiki pilot whose CN name the weapon's text mentions (signature weapons name their pilot)."""
    hits = [(len(name), pid) for name, pid in g.pilot_names if name in (text or '')]
    for _, pid in sorted(hits, reverse=True):
        if str(pid) in g.pilots:
            return g.pilots[str(pid)]['name']
    return ''


def weapon_range(g, w):
    """The attack's range from its grid shape (e.g. RingRhombus3to6 -> 3-6), and what the wiki's other weapons of the type say."""
    out = []
    skill = w['DefaultActiveSkill'] and g.row('ConfigDataActiveSkillInfo', w['DefaultActiveSkill'])
    if skill and skill['GridSelectFormType']:
        out.append(f'attack grid {strip(skill["GridSelectFormType"], "GridFormType_")}')
    kind = strip(w['Type'], 'EquipmentType_')
    seen = Counter(x['range'] for x in g.weapons.values() if x.get('type2') == kind and x.get('range'))
    if seen:
        out.append('other ' + kind + ' weapons in the wiki: ' + ', '.join(f'"{r}"' for r, _ in seen.most_common(3)))
    return seen.most_common(1)[0][0] if seen else '', '; '.join(out)


def weapon_basics(f, w, pilot=True, version=None):
    g = f.g
    kind = strip(w['Type'], 'EquipmentType_')
    rng, rng_note = weapon_range(g, w)
    f.add(f'- Weapon ID: {w["ID"]}',
          f'- CN name: {w["NameStrKey_EN"]}', '- EN name: ',
          f'- quality: {quality(w)}',
          f'- type1: {strip(w["Category"], "WeaponCategory_")}',
          f'- type2 / type: {kind}',
          f'- models: {sizes(w)}',
          f'- slot: {strip(w["WeaponEquipSlotLimit"], "WeaponEquipSlotLimitType_")}',
          f'- range: {rng}' + (f'  <!-- {rng_note}: check -->' if rng_note else ''),
          f'- weight: {w["Weight"]}', f'- atk: {w["AttackBase"]}', f'- hp: {int(w["HitValueBase"] or 0)}',
          f'- understanding: {int(w["CriticalAppendBase"] or 0)}', f'- grade: {w["Level"]}',
          f'- icon: {file_note(w["Icon"], "weapons", "icons", WEAPON_FOLDER.get(kind, kind))}')
    if pilot:
        guess = guess_pilot(g, w['DescStrKey_EN'])
        f.add(f'- pilot: {guess}' + ('  <!-- guessed from the description: check -->' if guess else ''),
              f'- Game version introduced: {version or ""}', '- ac (Armed Conquest season): ')
    f.add('', '#### Description', '<!-- → `describe` -->')
    f.text('', w['DescStrKey_EN'])


def weapon_passives(f, w):
    """The passives in the wiki's order: the signature ones, then the weapon type's own."""
    ids = jl(w['GlobalInitPassiveSkillIdList']) + jl(w['CarryEffectiveGlobalInitPassiveSkillIdList']) + jl(w['PassiveSkillIdList'])
    f.add(f'- passives: {ids}')
    for sid in ids:
        r = f.g.row('ConfigDataPassiveSkillInfo', sid)
        if r is None:
            f.add('', f'#### Passive {sid}', '- Not in the CN tables')
            continue
        if f.heading(f'#### Passive {sid}', sid):
            continue
        f.add(f'- Icon name: {file_note(r["Icon"], "unlisted", "pilot_skills")}')
        f.text('', r['SkillDescStrKey_EN'], name_cn=r['NameStrKey_EN'])


def weapon_form(g, wid, version):
    w = g.row('ConfigDataWeaponInfo', wid)
    if w is None:
        sys.exit(f'No weapon {wid} in the CN tables')
    recipe = g.recipe(wid)
    ur = recipe and recipe['SrcItemId'] and g.row('ConfigDataWeaponInfo', recipe['SrcItemId'])
    f = ItemForm(g)
    f.add(WEAPON_CHECKLIST, '', f'# Weapon {wid}: {w["NameStrKey_EN"]}' + (' (already in the wiki)' if str(wid) in g.weapons else ''))
    f.add('', f'## {quality(w)} weapon', '<!-- → data/db/weapons.json row, keyed by the weapon ID -->', '')
    weapon_basics(f, w, version=version)
    f.add('', '### Passives', '<!-- → data/db/skills.json rows (kind "weapon"), in this order in `passives` -->')
    weapon_passives(f, w)

    if ur:
        if str(ur['ID']) in g.weapons and not g.full:
            f.add('', f'## UR version {ur["ID"]}, already in the wiki: "{g.weapons[str(ur["ID"])]["name"]}"')
        else:
            f.add('', f'## UR version {ur["ID"]}', '<!-- → its own weapons.json row (quality "UR", no `pilot`),',
                  '     named like the others: "<base weapon> - B III" -->', '')
            weapon_basics(f, ur, pilot=False)
            f.add('', '### Passives')
            weapon_passives(f, ur)

    f.add('', '## Crafting (Arms Production)', '<!-- → `crafting` on each row -->')
    if recipe:
        f.add('', f'### {w["ID"]}')
        if recipe['SrcItemId']:
            note = 'its UR version' + (', already in the wiki' if str(recipe['SrcItemId']) in g.weapons else ', NEW (above)')
            f.ingredient(f'{{"weapon": "{recipe["SrcItemId"]}", "qty": 1}}', note)
        for m in jl(recipe['ExchangeMaterials']):
            f.material_line(m['ItemId'], m['Count'])
    else:
        f.add('- No Arms Production recipe in the CN tables')
    ur_recipe = ur and g.recipe(ur['ID'])
    if ur_recipe:
        f.add('', f'### {ur["ID"]} (UR)')
        for m in jl(ur_recipe['ExchangeMaterials']):
            f.material_line(m['ItemId'], m['Count'])

    f.materials_section()
    f.glossary_section()
    return f


# ── Backpacks ────────────────────────────────────────────────────────────────

def backpack_form(g, bid, version):
    b = g.row('ConfigDataBackpackInfo', bid)
    if b is None:
        sys.exit(f'No backpack {bid} in the CN tables')
    f = ItemForm(g)
    f.add(BACKPACK_CHECKLIST, '', f'# Backpack {bid}: {b["NameStrKey_EN"]}' + (' (already in the wiki)' if str(bid) in g.backpacks else ''))
    main = strip(b['MainBackPackType'], 'BackpackType_')
    f.add('', '## Basics', '<!-- → data/db/backpacks.json row, keyed by the backpack ID -->', '',
          f'- Backpack ID: {bid}',
          f'- CN name: {b["NameStrKey_EN"]}', '- EN name: ',
          f'- quality: {quality(b)}',
          f'- weight: {b["Weight"]}',
          f'- main_type: {main}',
          f'- st_type: {sizes(b)}',
          f'- icon: {file_note(b["Icon"], "backpacks", "icons")}')
    if main == 'Heal' and b['MainParam']:
        f.add(f'- repair: {b["MainParam"]}')
    if b['SubTypeStrKey_EN']:
        f.add(f'- Sub type (CN, the end of the skill name): {b["SubTypeStrKey_EN"]}')
    f.add(f'- Game version introduced: {version or ""}', '- ac (Armed Conquest season): ')

    f.add('', '## Skill', '<!-- → `skill`: { "id", "name", "icon", "effect" } -->')
    for sid in jl(b['PassiveSkillIds']):
        r = g.row('ConfigDataPassiveSkillInfo', sid)
        if r is None:
            f.add('', f'### Skill {sid}', '- Not in the CN tables')
            continue
        owner = g.backpack_skills.get(str(sid))
        if owner and not g.full:
            f.add('', f'### Skill {sid}, already in the wiki (backpack {owner[0]}: "{owner[1]}")')
            continue
        f.add('', f'### Skill {sid}', f'- Icon name: {file_note(r["Icon"], "unlisted", "pilot_skills")}')
        f.text('', r['SkillDescStrKey_EN'], name_cn=r['NameStrKey_EN'])

    f.add('', '## Crafting (Backpack Crafting)', '<!-- → `crafting`, as listed -->')
    rows = g.c.execute('select * from ConfigDataBackpackMakingFormulaInfo where BackpackProductID = ? order by ID', (bid,)).fetchall()
    if not rows:
        f.add('- No Backpack Crafting recipe in the CN tables')
    else:
        first = rows[0]
        def is_ur(backpack_id):
            r = g.row('ConfigDataBackpackInfo', backpack_id)
            return bool(r) and quality(r) == 'UR'

        for c in jl(first['BackpackIdCostList']):
            f.backpack_line(c['BackpackId'], c['Count'], is_ur(c['BackpackId']))
        composites = [jl(r['CostCompositeMaterialList'])[0] for r in rows if r['CostCompositeMaterialList']]
        if len(composites) > 1:
            f.ingredient('{"material": "random-composite", "qty": 1, "composite": true}', f'any of {len(composites)} Composite backpacks')
        elif composites:
            c = composites[0]
            if c['Type'] == 'ItemType_Backpack':
                f.backpack_line(c['Id'], c['Count'], is_ur(c['Id']))
            else:
                f.material_line(c['Id'], c['Count'])
        for r in jl(first['CostCustomRarityList']):
            key = RANDOM_BACKPACK.get(r['Rarity'])
            f.ingredient(f'{{"material": "{key or "<slug>"}", "qty": {r["Count"]}}}',
                         f'random {strip(r["Rarity"], "RarityType_")} backpacks' + ('' if key else ': NEW material'))
        if first['BluePrintItemID']:
            f.material_line(first['BluePrintItemID'], 1)

    f.materials_section()
    f.glossary_section()
    return f


# ── New items ────────────────────────────────────────────────────────────────

def new_ids(g):
    weapons, missing_ur = [], []
    for r in g.c.execute('select ResultItemId, SrcItemId from ConfigDataItemExchangeBlueprintInfo '
                         'where ItemType = "ItemType_Weapon" order by ID'):
        w = g.row('ConfigDataWeaponInfo', r['ResultItemId'])
        if not w or w['Rarity'] != 'RarityType_SSSR':
            continue
        if str(r['ResultItemId']) not in g.weapons:
            weapons.append(r['ResultItemId'])
        elif r['SrcItemId'] and str(r['SrcItemId']) not in g.weapons:
            missing_ur.append((r['ResultItemId'], r['SrcItemId']))
    backpacks = []
    for r in g.c.execute('select distinct BackpackProductID, NameStrKey_EN from ConfigDataBackpackMakingFormulaInfo '
                         'where BackpackProductBackpackType = "ItemType_Backpack" order by ID'):
        pid = r['BackpackProductID']
        if str(pid) not in g.backpacks and '作废' not in (r['NameStrKey_EN'] or '') and pid not in backpacks:
            backpacks.append(pid)
    return weapons, missing_ur, backpacks


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    ap.add_argument('ids', nargs='*', type=int, help='SSSR weapon IDs and/or backpack IDs (default: every new one)')
    ap.add_argument('--version', help='prefill "Game version introduced"')
    ap.add_argument('--full', action='store_true', help='ask for every text, even what the wiki already has')
    ap.add_argument('--force', action='store_true', help='overwrite existing forms')
    args = ap.parse_args()
    g = Items(full=args.full)
    if args.ids:
        weapons = [i for i in args.ids if g.row('ConfigDataWeaponInfo', i)]
        backpacks = [i for i in args.ids if i not in weapons]
    else:
        weapons, missing_ur, backpacks = new_ids(g)
        print(f'CN client has {len(weapons)} weapon(s) and {len(backpacks)} crafted backpack(s) the wiki doesn\'t')
        if missing_ur:
            print('  The wiki has these SSSR weapons but not their UR version (pass the SSSR ID for a form): '
                  + ', '.join(f'{s} (UR {u})' for s, u in missing_ur))
    for wid in weapons:
        weapon_form(g, wid, args.version).write(os.path.join(OUT, f'weapon-{wid}.md'), args.force)
    queue, done = list(backpacks), set()
    while queue:
        bid = queue.pop(0)
        if bid in done:
            continue
        done.add(bid)
        f = backpack_form(g, bid, args.version)
        f.write(os.path.join(OUT, f'backpack-{bid}.md'), args.force)
        queue += [b for b in f.new_backpacks if b not in done]


if __name__ == '__main__':
    main()
